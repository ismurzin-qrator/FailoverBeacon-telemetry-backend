CREATE TABLE IF NOT EXISTS events
(
    project_id LowCardinality(String) CODEC(ZSTD(3)),
    upload_id UUID,
    received_at DateTime64(3, 'UTC') CODEC(Delta(8), ZSTD(3)),
    event_time DateTime64(3, 'UTC') CODEC(Delta(8), ZSTD(3)),
    event_time_clamped Bool,
    delivery_delay Int64 CODEC(ZSTD(3)),
    ip_country LowCardinality(String) CODEC(ZSTD(3)),
    asn Nullable(UInt32),
    as_org LowCardinality(String) CODEC(ZSTD(3)),
    sim_country LowCardinality(String) CODEC(ZSTD(3)),
    sdk_version LowCardinality(String) CODEC(ZSTD(3)),
    app_package LowCardinality(String) CODEC(ZSTD(3)),
    app_version LowCardinality(String) CODEC(ZSTD(3)),
    os_api_level UInt64,

    format_version UInt8,
    call_id UInt64,
    resend_count UInt64,
    start_time UInt64 CODEC(Delta(8), ZSTD(3)),
    elapsed_time UInt64 CODEC(ZSTD(3)),
    sampling_fraction Float64,
    scheme LowCardinality(String) CODEC(ZSTD(3)),
    host LowCardinality(String) CODEC(ZSTD(3)),
    port Nullable(UInt16),
    method LowCardinality(String) CODEC(ZSTD(3)),
    phase LowCardinality(String) CODEC(ZSTD(3)),
    type LowCardinality(String) CODEC(ZSTD(3)),
    step LowCardinality(String) CODEC(ZSTD(3)),
    status_code Nullable(UInt16),
    protocol LowCardinality(String) CODEC(ZSTD(3)),
    server_ip String CODEC(ZSTD(3)),
    proxy LowCardinality(String) CODEC(ZSTD(3)),
    tls_version LowCardinality(String) CODEC(ZSTD(3)),
    tls_cipher LowCardinality(String) CODEC(ZSTD(3)),
    tls_issuer LowCardinality(String) CODEC(ZSTD(3)),
    reused_connection Bool,
    dns_addresses Array(String) CODEC(ZSTD(3)),
    timings_dns Nullable(UInt64),
    timings_connect Nullable(UInt64),
    timings_tls Nullable(UInt64),
    timings_send Nullable(UInt64),
    timings_wait Nullable(UInt64),
    timings_receive Nullable(UInt64),
    request_body_bytes Nullable(UInt64),
    response_content_length Nullable(Int64),
    response_body_bytes Nullable(UInt64),
    attempts Nested
    (
        ip String,
        proxy LowCardinality(String),
        elapsed_time Nullable(UInt64),
        result LowCardinality(String),
        type LowCardinality(String),
        step LowCardinality(String)
    ),
    network_state LowCardinality(String) CODEC(ZSTD(3)),
    network_transport LowCardinality(String) CODEC(ZSTD(3)),
    network_vpn Nullable(Bool),
    network_validated Nullable(Bool),
    network_captive_portal Nullable(Bool),
    network_metered Nullable(Bool),
    network_roaming Nullable(Bool),
    network_downstream_kbps Nullable(UInt64),
    network_upstream_kbps Nullable(UInt64),
    network_signal_strength Nullable(Int64),
    network_blocked Nullable(Bool),
    network_carrier_name LowCardinality(String) CODEC(ZSTD(3)),
    network_carrier_mcc LowCardinality(String) CODEC(ZSTD(3)),
    network_carrier_mnc LowCardinality(String) CODEC(ZSTD(3)),
    network_carrier_carrier_id Nullable(UInt64),
    network_carrier_network_type Nullable(UInt64),
    foreground Nullable(Bool),
    failover LowCardinality(String) CODEC(ZSTD(3)),

    weight Float64 MATERIALIZED 1 / sampling_fraction,
    wq UInt64 MATERIALIZED toUInt64(round(1000 / sampling_fraction)),
    outcome LowCardinality(String) MATERIALIZED multiIf(
        type = 'ok' AND NOT has(attempts.result, 'failed'), 'success',
        type = 'ok', 'recovered',
        type = 'http.error', 'http_error',
        type = 'abandoned', 'abandoned',
        'network')
)
ENGINE = ReplacingMergeTree
PARTITION BY toDate(event_time)
ORDER BY (project_id, toDate(event_time), host, call_id, resend_count, start_time)
TTL toDate(event_time) + INTERVAL 90 DAY
SETTINGS ttl_only_drop_parts = 1
